ok('L12 H01', '150/5=30; 11175/10=1117,5', F(150,5) == 30 and F(11175,10) == F(2235,2))
ok('L12 H01', 'R(30)=870/2=435; R(31)=930/2=465=435+30', R(30) == F(870,2) == 435 and R(31) == F(930,2) == 465 == 435+30)
ok('L12 H01', 't(6)=24; t(16)=8; t(51)=2,4; t(151)=0,8; t(61)=2', t(6) == 24 and t(16) == 8 and t(51) == F(24,10) and t(151) == F(8,10) and t(61) == 2)
ok('L12 H01', '5,25,125,625; 125<150<625', [5**k for k in (1,2,3,4)] == [5,25,125,625] and 125 < 150 < 625)

mal = [a for a in A if not a[2]]
for h, tx, c in A: print('OK   ' if c else 'ERROR', h, '·', tx)
print('\n%d afirmaciones revisadas, %d con error' % (len(A), len(mal)))
raise SystemExit(1 if mal else 0)
