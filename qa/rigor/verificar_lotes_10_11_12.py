ok('L10 H01', '3/4÷1/8=3/4·8=24/4=6; 6·1/8=6/8=3/4', F(3,4)/F(1,8) == F(24,4) == 6 and 6*F(1,8) == F(3,4))
ok('L10 H01', '1/2+1/2=1; 4/4=1/4·4=1; 1/(1/4)=4', F(1,2)+F(1,2) == 1 and F(1,4)*4 == 1 and 1/F(1,4) == 4)
# Lote 10 H02 Mixtos
ok('L10 H02', '11=4·2+3; 11/4=2 3/4', 11 == 4*2+3 and F(11,4) == 2+F(3,4))
ok('L10 H02', '3 2/5=17/5; 7/4=1 3/4; 2 1/4=9/4', 3+F(2,5) == F(17,5) and F(7,4) == 1+F(3,4) and 2+F(1,4) == F(9,4))
ok('L10 H02', '9/4 h·60=540/4=135 min=120+15', F(9,4)*60 == F(540,4) == 135 == 120+15)
ok('L10 H02', '3/2+11/4=6/4+11/4=17/4=4 1/4; falta 1/4 m=25 cm', F(3,2)+F(11,4) == F(17,4) == 4+F(1,4) and (F(17,4)-4)*100 == 25)
# Lote 10 H03 Combinadas
ok('L10 H03', '1/2+1/2·4=5/2; (1/2+1/2)·4=4', F(1,2)+F(1,2)*4 == F(5,2) and (F(1,2)+F(1,2))*4 == 4)
ok('L10 H03', '(1/2+1/4)^2÷3/8−1/2: 3/4, 9/16, 72/48=3/2, 1', F(1,2)+F(1,4) == F(3,4) and F(3,4)**2 == F(9,16) and F(9,16)*F(8,3) == F(72,48) == F(3,2) and F(3,2)-F(1,2) == 1)
ok('L10 H03', '(2+4)/3=2', F(2+4,3) == 2)
ok('L10 H03', '1/2+3·1/4=5/4=1 1/4', F(1,2)+3*F(1,4) == F(5,4) == 1+F(1,4))
ok('L10 H03', '(5−4·3/4)·1/2=1', (5-4*F(3,4))*F(1,2) == 1 and 4*F(3,4) == 3)
ok('L10 H03', '(4·3/2+3/4)÷3=27/4·1/3=27/12=9/4=2h15', 4*F(3,2) == 6 and 6+F(3,4) == F(27,4) and F(27,4)/3 == F(27,12) == F(9,4) and F(9,4)*60 == 135 == 2*60+15)
# Lote 10 H04 Propiedades de la adición
ok('L10 H04', '3/4+1/2=1/2+3/4=5/4=1 1/4', F(3,4)+F(1,2) == F(1,2)+F(3,4) == F(5,4))
ok('L10 H04', '(1/3+1/4)+3/4=7/12+9/12=16/12=4/3=1/3+(1/4+3/4)', (F(1,3)+F(1,4)) == F(7,12) and F(7,12)+F(9,12) == F(16,12) == F(4,3) == F(1,3)+1)
ok('L10 H04', '−5/2+5/2=0; 3/4−1/4=2/4; 1/4−3/4=−2/4', -F(5,2)+F(5,2) == 0 and F(3,4)-F(1,4) == F(2,4) and F(1,4)-F(3,4) == -F(2,4))
# Lote 10 H05 Propiedades de la multiplicación
ok('L10 H05', '1/2·(2/3+4/3)=1=1/3+2/3', F(1,2)*(F(2,3)+F(4,3)) == 1 and F(1,2)*F(2,3) == F(1,3) and F(1,2)*F(4,3) == F(2,3))
ok('L10 H05', '1/2·3/4=3/4·1/2=3/8 kg=375 g', F(1,2)*F(3,4) == F(3,8) and F(3,8)*1000 == 375)
ok('L10 H05', '6·(1/4+1/2)=6·3/4=18/4=9/2=6/4+6/2=3/2+3', 6*(F(1,4)+F(1,2)) == F(18,4) == F(9,2) == F(6,4)+F(6,2) == F(3,2)+3)
ok('L10 H05', '5/2·2/5=10/10=1; 5/2=2 1/2', F(5,2)*F(2,5) == 1 and F(5,2) == 2+F(1,2))
# Lote 11 H01
ok('L11 H01', '2^3=8; 1,5^2=2,25; 2^-3=1/8; 400/8=50', 2**3 == 8 and F(3,2)**2 == F(225,100) and F(2)**-3 == F(1,8) and 400*F(1,8) == 50)
ok('L11 H01', '(−3)^2=9; (−3)^3=−27; −3^2=−9', (-3)**2 == 9 and (-3)**3 == -27 and -(3**2) == -9)
ok('L11 H01', '3^4=81; 2^6=64; 18/6=3', 3**4 == 81 and 2**6 == 64 and 18/6 == 3)
ok('L11 H01', '9^(1/2)=3; 8^(2/3)=cbrt(64)=4; (−8)^(1/3)=−2; (−8)^2=64', 3*3 == 9 and 8**2 == 64 and 4**3 == 64 and (-2)**3 == -8 and (-8)**2 == 64)
ok('L11 H01', '2^1,4≈2,639; 2^1,41≈2,657; 2^1,414≈2,665; 2^√2≈2,665', cerca(2**1.4, 2.639) and cerca(2**1.41, 2.657) and cerca(2**1.414, 2.665) and cerca(2**math.sqrt(2), 2.665))
# Lote 11 H02
ok('L11 H02', '3^2·4^2=12^2=144=9·16', 3**2*4**2 == 12**2 == 144 == 9*16)
ok('L11 H02', '6^3÷2^3=3^3=27=216÷8', F(6**3, 2**3) == 3**3 == 27 and 6**3 == 216 and 2**3 == 8)
ok('L11 H02', '2^3·5^3=10^3=1000; (2+3)^2=25≠13', 2**3*5**3 == 10**3 == 1000 and (2+3)**2 == 25 and 2**2+3**2 == 13)
# Lote 11 H03
ok('L11 H03', '(2/3)^4=16/81; 81·16/81=16; 81,54,36,24,16', F(2,3)**4 == F(16,81) and [81*F(2,3)**k for k in range(5)] == [81,54,36,24,16])
ok('L11 H03', '(3/4)^2=9/16; 16000·9/16=9000; 16000,12000,9000', F(3,4)**2 == F(9,16) and 16000*F(9,16) == 9000 and 16000*F(3,4) == 12000)
ok('L11 H03', '(2/5)^-2=(5/2)^2=25/4=6 1/4; 4/25·25/4=1; (2/3)^-2=9/4', F(2,5)**-2 == F(25,4) == 6+F(1,4) and F(4,25)*F(25,4) == 1 and F(2,3)**-2 == F(9,4))
ok('L11 H03', '(1/2)^2=1/4<1/2; (3/2)^2=9/4>3/2', F(1,2)**2 == F(1,4) < F(1,2) and F(3,2)**2 == F(9,4) > F(3,2))
# Lote 11 H04
ok('L11 H04', '(2/3)^2·(2/3)^3=(2/3)^5=32/243; 243·32/243=32', F(2,3)**2*F(2,3)**3 == F(2,3)**5 == F(32,243) and 243*F(32,243) == 32)
ok('L11 H04', '(1/2)^5÷(1/2)^3=(1/2)^2=1/4=1/32÷1/8=8/32', F(1,2)**5/F(1,2)**3 == F(1,4) == F(1,32)/F(1,8) == F(8,32))
ok('L11 H04', '(3/4)^2·(2/3)^2=(6/12)^2=(1/2)^2=1/4=9/16·4/9=36/144', F(3,4)**2*F(2,3)**2 == F(1,4) == F(9,16)*F(4,9) == F(36,144) and F(3,4)*F(2,3) == F(6,12) == F(1,2))
ok('L11 H04', '(3/4)^3·(2/3)^3=(1/2)^3=1/8', F(3,4)**3*F(2,3)**3 == F(1,8))
# Lote 11 H05
ok('L11 H05', '2^5·2^10=2^15=32·1024=32768', 2**5*2**10 == 2**15 == 32*1024 == 32768)
ok('L11 H05', '2^9÷2^6=2^3=8=512÷64', F(2**9, 2**6) == 8 and 2**9 == 512 and 2**6 == 64)
ok('L11 H05', '10^6÷10^2=10^4=10000; 2^3+2^2=12≠32=2^5; (a^2)^3=a^6', 10**6//10**2 == 10**4 == 10000 and 2**3+2**2 == 12 and 2**5 == 32 and (7**2)**3 == 7**6)
# Lote 12 H01 Dunbar
R = lambda n: F(n*(n-1), 2)
t = lambda n: F(120, n-1)
ok('L12 H01', 'R(5)=10; R(15)=105; R(50)=1225; R(150)=11175', [R(5), R(15), R(50), R(150)] == [10, 105, 1225, 11175])
